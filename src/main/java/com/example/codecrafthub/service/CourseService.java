package com.example.codecrafthub.service;

import com.example.codecrafthub.exception.CourseFileException;
import com.example.codecrafthub.exception.CourseNotFoundException;
import com.example.codecrafthub.model.Course;
import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.springframework.stereotype.Service;

import java.io.IOException;
import java.nio.file.AtomicMoveNotSupportedException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.nio.file.StandardCopyOption;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;

/**
 * Service layer for course operations.
 *
 * This class handles:
 *
 * - Reading courses from courses.json
 * - Writing courses to courses.json
 * - Creating courses
 * - Updating courses
 * - Deleting courses
 * - Finding courses
 */
@Service
public class CourseService {

    /**
     * The JSON file is stored in the application project directory.
     */
    private final Path coursesFile = Paths.get("courses.json");

    /**
     * Jackson is used to convert between Java objects and JSON.
     */
    private final ObjectMapper objectMapper;

    public CourseService(ObjectMapper objectMapper) {
        this.objectMapper = objectMapper;

        // Create courses.json automatically when the application starts.
        initializeFile();
    }

    /**
     * Returns all courses from the JSON file.
     */
    public synchronized List<Course> getAllCourses() {
        return readCourses();
    }

    /**
     * Returns one course by ID.
     *
     * @throws CourseNotFoundException if no course exists with the given ID
     */
    public synchronized Course getCourseById(Long id) {
        return readCourses()
                .stream()
                .filter(course -> course.getId().equals(id))
                .findFirst()
                .orElseThrow(() ->
                        new CourseNotFoundException("Course with id " + id + " was not found"));
    }

    /**
     * Creates a new course.
     *
     * The ID starts at 1 and increases automatically.
     */
    public synchronized Course createCourse(Course course) {
        List<Course> courses = readCourses();

        long nextId = courses.stream()
                .map(Course::getId)
                .filter(id -> id != null)
                .max(Comparator.naturalOrder())
                .orElse(0L) + 1;

        course.setId(nextId);

        // The creation timestamp is generated by the server.
        course.setCreatedAt(Instant.now());

        courses.add(course);
        writeCourses(courses);

        return course;
    }

    /**
     * Updates an existing course.
     *
     * The ID and created_at values cannot be changed by the client.
     */
    public synchronized Course updateCourse(Long id, Course updatedCourse) {
        List<Course> courses = readCourses();

        Course existingCourse = courses.stream()
                .filter(course -> course.getId().equals(id))
                .findFirst()
                .orElseThrow(() ->
                        new CourseNotFoundException("Course with id " + id + " was not found"));

        // Preserve server-controlled values.
        updatedCourse.setId(existingCourse.getId());
        updatedCourse.setCreatedAt(existingCourse.getCreatedAt());

        int courseIndex = courses.indexOf(existingCourse);
        courses.set(courseIndex, updatedCourse);

        writeCourses(courses);

        return updatedCourse;
    }

    /**
     * Deletes an existing course.
     */
    public synchronized void deleteCourse(Long id) {
        List<Course> courses = readCourses();

        boolean removed = courses.removeIf(course -> course.getId().equals(id));

        if (!removed) {
            throw new CourseNotFoundException(
                    "Course with id " + id + " was not found"
            );
        }

        writeCourses(courses);
    }

    /**
     * Reads the complete list of courses from courses.json.
     */
    private List<Course> readCourses() {
        try {
            // An empty file is treated as an empty course list.
            if (Files.size(coursesFile) == 0) {
                return new ArrayList<>();
            }

            return objectMapper.readValue(
                    coursesFile.toFile(),
                    new TypeReference<List<Course>>() {
                    }
            );

        } catch (IOException | RuntimeException exception) {
            throw new CourseFileException(
                    "Unable to read courses from " + coursesFile.toAbsolutePath(),
                    exception
            );
        }
    }

    /**
     * Writes the complete course list to courses.json.
     *
     * A temporary file is written first. Then it replaces courses.json.
     * This helps avoid leaving a partially written JSON file.
     */
    private void writeCourses(List<Course> courses) {
        Path temporaryFile = Paths.get("courses.json.tmp");

        try {
            objectMapper
                    .writerWithDefaultPrettyPrinter()
                    .writeValue(temporaryFile.toFile(), courses);

            try {
                // ATOMIC_MOVE is safer when the file system supports it.
                Files.move(
                        temporaryFile,
                        coursesFile,
                        StandardCopyOption.REPLACE_EXISTING,
                        StandardCopyOption.ATOMIC_MOVE
                );
            } catch (AtomicMoveNotSupportedException exception) {
                // Fall back to a normal replacement if atomic moves are unsupported.
                Files.move(
                        temporaryFile,
                        coursesFile,
                        StandardCopyOption.REPLACE_EXISTING
                );
            }

        } catch (IOException | RuntimeException exception) {
            try {
                Files.deleteIfExists(temporaryFile);
            } catch (IOException ignored) {
                // There is nothing useful to do if cleanup also fails.
            }

            throw new CourseFileException(
                    "Unable to write courses to " + coursesFile.toAbsolutePath(),
                    exception
            );
        }
    }

    /**
     * Creates courses.json and its parent directory if necessary.
     */
    private void initializeFile() {
        try {
            Path parentDirectory = coursesFile.getParent();

            if (parentDirectory != null) {
                Files.createDirectories(parentDirectory);
            }

            if (Files.notExists(coursesFile)) {
                objectMapper.writeValue(coursesFile.toFile(), new ArrayList<Course>());
            }

        } catch (IOException | RuntimeException exception) {
            throw new CourseFileException(
                    "Unable to create " + coursesFile.toAbsolutePath(),
                    exception
            );
        }
    }
}